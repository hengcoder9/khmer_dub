<?php
// One-time setup: creates config.php, the database + tables, default plans, and the first admin account.
//   CLI:  php install.php --admin-email=you@example.com --admin-password=secret123 [--db-user=root --db-pass= --db-name=khmerdub]
//   Web:  open /khmerdub/install.php once (it refuses to run again after an admin exists).
declare(strict_types=1);

$cli = PHP_SAPI === 'cli';
$opts = $cli ? getopt('', ['admin-email:', 'admin-password:', 'admin-name::', 'db-host::', 'db-port::', 'db-user::', 'db-pass::', 'db-name::']) : $_POST;
$get = fn($k, $d = '') => trim((string)($opts[$k] ?? $opts[str_replace('-', '_', $k)] ?? $d));

function out(string $msg, bool $ok = true): void
{
    global $cli;
    if ($cli) {
        fwrite($ok ? STDOUT : STDERR, $msg . PHP_EOL);
        if (!$ok) exit(1);
        return;
    }
    echo '<p style="color:' . ($ok ? '#047857' : '#b91c1c') . '">' . htmlspecialchars($msg) . '</p>';
    if (!$ok) exit;
}

$configPath = __DIR__ . '/config.php';
$cfg = is_file($configPath) ? require $configPath : require __DIR__ . '/config.sample.php';

if (!$cli && $_SERVER['REQUEST_METHOD'] !== 'POST') {
    // only offer the web form while no admin exists
    try {
        $pdo = new PDO("mysql:host={$cfg['db']['host']};port={$cfg['db']['port']};dbname={$cfg['db']['name']}", $cfg['db']['user'], $cfg['db']['pass']);
        if ($pdo->query("SELECT COUNT(*) FROM users WHERE role = 'admin'")->fetchColumn() > 0) exit('Already installed. Delete install.php from the server.');
    } catch (Throwable) {
    }
    echo '<!doctype html><meta charset="utf-8"><title>KhmerDub server setup</title><body style="font-family:system-ui;max-width:520px;margin:40px auto">
    <h2>KhmerDub account server — setup</h2><form method="post" style="display:grid;gap:8px">
    <b>Database</b><input name="db_host" value="127.0.0.1"><input name="db_port" value="3306"><input name="db_name" value="khmerdub">
    <input name="db_user" value="root"><input name="db_pass" type="password" placeholder="MySQL password (empty for XAMPP)">
    <b>First admin</b><input name="admin_email" type="email" placeholder="admin email" required><input name="admin_name" placeholder="name">
    <input name="admin_password" type="password" placeholder="password (min 8)" minlength="8" required><button>Install</button></form>';
    exit;
}

$db = [
    'host' => $get('db-host', $cfg['db']['host']),
    'port' => (int)$get('db-port', (string)$cfg['db']['port']),
    'name' => preg_replace('/[^A-Za-z0-9_]/', '', $get('db-name', $cfg['db']['name'])),
    'user' => $get('db-user', $cfg['db']['user']),
    'pass' => $opts['db-pass'] ?? $opts['db_pass'] ?? $cfg['db']['pass'],
];
$email = strtolower($get('admin-email'));
$pw = (string)($opts['admin-password'] ?? $opts['admin_password'] ?? '');
if (!filter_var($email, FILTER_VALIDATE_EMAIL)) out('Admin email is missing or invalid (--admin-email=…)', false);
if (strlen($pw) < 8) out('Admin password must be at least 8 characters (--admin-password=…)', false);

try {
    $pdo = new PDO("mysql:host={$db['host']};port={$db['port']};charset=utf8mb4", $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
} catch (Throwable $e) {
    out('Cannot connect to MySQL: ' . $e->getMessage() . ' — is MySQL running in XAMPP?', false);
}
// Shared hosting (cPanel) creates the database in its own panel and the DB user may not hold CREATE rights,
// so use an existing database first and only try to create it when it is missing (XAMPP).
try {
    $pdo->exec("USE `{$db['name']}`");
} catch (Throwable $e) {
    try {
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$db['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $pdo->exec("USE `{$db['name']}`");
    } catch (Throwable $e2) {
        out("Cannot open database `{$db['name']}`: " . $e->getMessage() . ' — on cPanel, create it under MySQL Databases, add the user to it with ALL PRIVILEGES, and use the full name (usually <cpaneluser>_name).', false);
    }
}
foreach (array_filter(array_map('trim', explode(";\n", file_get_contents(__DIR__ . '/lib/schema.sql')))) as $sql) {
    if (preg_replace('/^\s*--.*$/m', '', $sql) !== '') $pdo->exec($sql);
}
out("Database `{$db['name']}` ready.");

if ($pdo->query("SELECT COUNT(*) FROM users WHERE role = 'admin'")->fetchColumn() > 0 && !$cli) out('An admin already exists — nothing else to do.', false);
$st = $pdo->prepare("INSERT INTO users (email, name, password_hash, role, status, created_at) VALUES (?, ?, ?, 'admin', 'active', UTC_TIMESTAMP())
                     ON DUPLICATE KEY UPDATE role = 'admin', status = 'active', password_hash = VALUES(password_hash)");
$st->execute([$email, $get('admin-name') ?: 'Admin', password_hash($pw, PASSWORD_DEFAULT)]);
out("Admin account: $email");

if (!is_file($configPath)) {
    $cfg['db'] = $db;
    file_put_contents($configPath, "<?php\n// generated by install.php — keep this file private\nreturn " . var_export($cfg, true) . ";\n");
    out('Wrote config.php');
}
out('Done. Admin panel: /khmerdub/admin/  ·  API: /khmerdub/api/health');
